import copy
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'scripts'))
from validate_research import CONTRACT, KINDS, REFERENCES, SCHEMAS, intake_errors, validate_tree


class ContractAdoption(unittest.TestCase):
    def test_import_hashes(self):
        manifest = json.loads((CONTRACT / 'IMPORT_MANIFEST.json').read_text())
        for item in manifest['files']:
            with self.subTest(path=item['path']):
                self.assertEqual(hashlib.sha256((CONTRACT / item['path']).read_bytes()).hexdigest(), item['sha256'])

    def test_all_kinds_have_issue_coverage(self):
        mapping = json.loads((ROOT / 'research/component-issues.json').read_text())
        self.assertEqual(set(mapping), set(KINDS))
        self.assertTrue(all(isinstance(n, int) and n > 0 for n in mapping.values()))

    def test_reference_fields_are_covered(self):
        found = {(kind, field) for kind in KINDS for field in SCHEMAS['catalog-item.schema.json']['$defs'][f'spec_{kind}']['properties'] if field.endswith(('_ref', '_refs'))}
        # v1 leaves license_ref as an opaque string with no license registry/kind.
        self.assertEqual(set(REFERENCES) | {('model', 'license_ref')}, found)

    def test_generators_reproduce_contract(self):
        with tempfile.TemporaryDirectory() as temp:
            clone = Path(temp) / 'contract'
            shutil.copytree(CONTRACT, clone, ignore=shutil.ignore_patterns('__pycache__'))
            env = dict(os.environ, PYTHONUTF8='1')
            for script in ('generate_schemas.py', 'create_examples.py', 'generate_component_docs.py'):
                subprocess.run([sys.executable, str(clone / 'reference' / script)], check=True, capture_output=True, env=env)
            # Evaluation report is generated by the reference interpreter separately.
            subprocess.run([sys.executable, str(clone / 'reference/evaluate.py'), '--build', str(clone / 'examples/build.json'), '--catalog', str(clone / 'examples/catalog.json'), '--rules', str(clone / 'examples/ruleset.json'), '--resource', str(clone / 'examples/resource-estimate.json'), '--cost', str(clone / 'examples/cost-estimate.json'), '--output', str(clone / 'examples/evaluation-report.json')], check=True, capture_output=True, env=env)
            for directory in ('schemas', 'baseline', 'examples'):
                for path in (CONTRACT / directory).glob('*.json'):
                    with self.subTest(path=path.name):
                        self.assertEqual(json.loads(path.read_text(encoding='utf-8')), json.loads((clone / path.relative_to(CONTRACT)).read_text(encoding='utf-8')))
            self.assertEqual((CONTRACT / 'docs/COMPONENTS.md').read_text(encoding='utf-8'), (clone / 'docs/COMPONENTS.md').read_text(encoding='utf-8'))


class Intake(unittest.TestCase):
    def setUp(self):
        # Test-only data: these are never placed in the research proposal directories.
        self.item = {'schema_version': '1.0.0', 'id': 'test.provider', 'kind': 'model_provider', 'tier': 'T1', 'name': 'Test provider', 'version': '1', 'status': 'active', 'billing_class': 'unknown', 'spec': {}, 'provenance': [{'source_uri': 'https://github.com/Pick-Your-AI/research', 'checked_at': '2026-10-16T09:00:00Z', 'verification_status': 'unverified'}], 'updated_at': '2026-10-16T09:00:00Z'}

    def test_valid_shape_does_not_require_verified_claim(self):
        self.assertEqual(intake_errors([self.item], []), [])

    def test_missing_and_synthetic_sources_rejected(self):
        for uri in (None, 'https://models.example/model', 'https://example.com/x', 'https://user:password@host.com/doc'):
            item = copy.deepcopy(self.item)
            if uri is None:
                item['provenance'][0].pop('source_uri')
            else:
                item['provenance'][0]['source_uri'] = uri
            self.assertTrue(intake_errors([item], []))

    def test_unknown_field_and_duplicate_ids_rejected(self):
        self.assertTrue(intake_errors([self.item, self.item], []))
        self.item['spec']['unsupported_claim'] = True
        self.assertTrue(intake_errors([self.item], []))

    def test_tier_and_fixture_id_rejected(self):
        self.item['tier'] = 'T2'
        self.assertTrue(intake_errors([self.item], []))
        self.item['tier'] = 'T1'
        self.item['id'] = 'cat.provider.fixture'
        self.assertTrue(intake_errors([self.item], []))

    def test_unresolved_and_wrong_kind_reference_rejected(self):
        item = copy.deepcopy(self.item)
        item.update(id='test.profile', kind='compute_profile', tier='T2', spec={'hosting_ref': 'test.provider', 'cpu_cores': 8, 'ram_gb': 16, 'region': 'test-region'})
        self.assertTrue(intake_errors([item], []))
        self.assertTrue(intake_errors([self.item, item], []))

    def test_price_version_dates_and_duplicate_rates(self):
        rate = {'id': 'test.rate', 'catalog_item_id': self.item['id'], 'catalog_item_version': '1', 'meter': 'request', 'unit_price': {'amount': '0.1', 'currency': 'USD'}, 'valid_from': '2026-10-16T09:00:00Z', 'provenance': self.item['provenance'][0], 'price_type': 'estimate'}
        book = {'schema_version': '1.0.0', 'id': 'test.prices', 'revision': 1, 'captured_at': '2026-10-16T09:00:00Z', 'rates': [rate]}
        self.assertEqual(intake_errors([self.item], [book]), [])
        rate['catalog_item_version'] = 'missing'
        self.assertTrue(intake_errors([self.item], [book]))
        rate['catalog_item_version'] = '1'
        rate['valid_until'] = rate['valid_from']
        self.assertTrue(intake_errors([self.item], [book]))
        rate.pop('valid_until')
        book['rates'].append(copy.deepcopy(rate))
        self.assertTrue(intake_errors([self.item], [book]))

    def test_malformed_json_and_signed_manifest_fail(self):
        with tempfile.TemporaryDirectory() as temp:
            root = Path(temp)
            (root / 'catalog/proposals').mkdir(parents=True)
            bad = root / 'catalog/proposals/bad.json'
            bad.write_text('{')
            self.assertTrue(validate_tree(root)[0])
            bad.unlink()
            (root / 'evidence').mkdir()
            manifest = {'id': 'test.artifact', 'uri': 'https://host.com/data?signature=secret', 'version': '1', 'sha256': 'a' * 64, 'access': 'restricted', 'description': 'Test only', 'rights': 'Test only'}
            (root / 'evidence/test.json').write_text(json.dumps(manifest))
            self.assertTrue(validate_tree(root)[0])
            manifest['uri'] = 's3://test-bucket/data'
            (root / 'evidence/test.json').write_text(json.dumps(manifest))
            self.assertEqual(validate_tree(root)[0], [])


if __name__ == '__main__':
    unittest.main()
